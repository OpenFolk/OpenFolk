export type TextKey = Key;

const DICTIONARIES: Record<Language, Record<Key, string>> = { en, de };

let source: () => Language = () => 'en';

/** Registered by settings.ts; kept as a callback so this module has no imports (it is used everywhere). */
export function setLanguageSource(get: () => Language): void {
    source = get;
}

export function language(): Language {
    try {
        const l = source();
        return l in DICTIONARIES ? l : 'en';
    } catch {
        return 'en';
    }
}

/** Text in the current language (or `lang`), placeholders {name} filled from `params`. */
export function t(key: Key, params: Record<string, string | number> = {}, lang: Language = language()): string {
    const text = DICTIONARIES[lang]?.[key] ?? en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

/** Locale for dates and times in texts of the current language. */
export function locale(lang: Language = language()): string {
    return lang === 'de' ? 'de-DE' : 'en-GB';
}
