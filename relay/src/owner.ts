// Who the relay belongs to: the password of the web app and the token of the backends, kept only as hashes.
// They come from the environment (USER_PASSWORD, AGENT_TOKEN) or from a claim: a relay started without them waits,
// prints a setup code to its log, and the first backend that sends that code together with its own two tokens
// (npm run claim) owns it. The code is in the log only, so only whoever runs the relay can hand it on.

import { randomBytes, randomInt } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { checkPassword, hashPassword, hashToken, isLegacyHash, PASSWORD_HASH, tokenEquals, tokenMatches } from './auth.ts';

export interface Credentials {
    clientHash: string;
    agentHash: string;
}

export type ClaimResult = 'ok' | 'wrong_code' | 'invalid' | 'already_claimed';

export const OWNER_FILE = 'owner.json';
/** Both tokens are generated by the backend with 64 characters; whoever sets them by hand needs at least this many. */
export const MIN_TOKEN_LENGTH = 16;
const MAX_TOKEN_LENGTH = 256;
/** Without I, O, 0 and 1, which are easy to misread from a log: 32 characters, 5 bits each. */
const CODE_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

/** A setup code of 10 characters (50 bits) as XXXXX-XXXXX. */
export function newSetupCode(): string {
    let s = '';
    for (let i = 0; i < 10; i++) s += CODE_ALPHABET[randomInt(CODE_ALPHABET.length)];
    return `${s.slice(0, 5)}-${s.slice(5)}`;
}

/** Upper case without separators, so "abcde fghjk" and "ABCDE-FGHJK" match. */
export function normalizeCode(code: string): string {
    return code.toUpperCase().replace(/[^A-Z0-9]/g, '');
}

/** Passwords set by hand before the minimum was raised; such a relay keeps starting, with a warning in its log. */
const LEGACY_PASSWORD_LENGTH = 8;

function validToken(t: string): boolean {
    return t.length >= MIN_TOKEN_LENGTH && t.length <= MAX_TOKEN_LENGTH && !/\s/.test(t);
}

export class Owner {
    /** null while the relay is unclaimed. */
    credentials: Credentials | null = null;
    /** Code a backend needs to claim the relay; '' once it is claimed. */
    setupCode = '';
    /** Something to say in the start log (a password shorter than recommended). */
    warning = '';
    private file: string;

    /** Throws when only one token is set or one is too short: a relay that half-starts helps nobody. */
    constructor(dataDir: string, clientToken = '', agentToken = '', setupCode = '') {
        this.file = path.join(dataDir, OWNER_FILE);
        if (clientToken || agentToken) {
            if (!clientToken || !agentToken) throw new Error('Set both USER_PASSWORD and AGENT_TOKEN, or neither (then a backend claims the relay with the setup code).');
            if (clientToken.length < LEGACY_PASSWORD_LENGTH) throw new Error(`USER_PASSWORD needs at least ${MIN_TOKEN_LENGTH} characters.`);
            if (clientToken.length < MIN_TOKEN_LENGTH) {
                this.warning = `USER_PASSWORD has fewer than ${MIN_TOKEN_LENGTH} characters; choose a longer one (pairing links make it rarely needed).`;
            }
            if (agentToken.length < MIN_TOKEN_LENGTH) throw new Error(`AGENT_TOKEN needs at least ${MIN_TOKEN_LENGTH} characters.`);
            this.credentials = { clientHash: hashPassword(clientToken), agentHash: hashToken(agentToken) };
            return;
        }
        this.credentials = this.load();
        if (this.credentials) return;
        if (setupCode && normalizeCode(setupCode).length < 10) throw new Error('RELAY_SETUP_CODE needs at least 10 letters or digits.');
        this.setupCode = setupCode.trim() || newSetupCode();
    }

    private load(): Credentials | null {
        try {
            const v = JSON.parse(fs.readFileSync(this.file, 'utf8')) as Partial<Credentials>;
            return typeof v.clientHash === 'string' && PASSWORD_HASH.test(v.clientHash) && typeof v.agentHash === 'string' && /^[0-9a-f]{64}$/.test(v.agentHash)
                ? { clientHash: v.clientHash, agentHash: v.agentHash } : null;
        } catch {
            return null;
        }
    }

    claim(code: string, clientToken: string, agentToken: string): ClaimResult {
        if (this.credentials) return 'already_claimed';
        if (!tokenEquals(normalizeCode(code), normalizeCode(this.setupCode))) return 'wrong_code';
        if (!validToken(clientToken) || !validToken(agentToken)) return 'invalid';
        const credentials = { clientHash: hashPassword(clientToken), agentHash: hashToken(agentToken) };
        this.save({ ...credentials, claimedAt: new Date().toISOString() });
        this.credentials = credentials;
        this.setupCode = '';
        return 'ok';
    }

    /** The web app's password; a claim's SHA-256 hash from before scrypt is replaced by the first sign-in with it. */
    passwordMatches(raw: string): boolean {
        const c = this.credentials;
        if (!c || !checkPassword(c.clientHash, raw)) return false;
        if (isLegacyHash(c.clientHash)) {
            c.clientHash = hashPassword(raw);
            let stored: Record<string, unknown> = {};
            try {
                stored = JSON.parse(fs.readFileSync(this.file, 'utf8')) as Record<string, unknown>;
            } catch { /* rewritten below */ }
            this.save({ ...stored, clientHash: c.clientHash });
        }
        return true;
    }

    private save(data: object): void {
        fs.mkdirSync(path.dirname(this.file), { recursive: true });
        fs.writeFileSync(this.file, JSON.stringify(data, null, 2), { mode: 0o600 });
    }
}

export const MACHINE_TOKENS_FILE = 'machine-tokens.json';
/** How long an invitation for a machine works. */
const INVITE_MS = 15 * 60_000;

/**
 * Machines joined by invitation: each has an agent token of its own, valid for its machine name only, kept as a hash.
 * The shared AGENT_TOKEN keeps working next to them. An invitation is a one-time token, kept in memory only: a
 * restart of the relay voids open invitations.
 */
export class MachineTokens {
    private file: string;
    private list: { machine: string; hash: string; created: string }[] = [];
    private invites = new Map<string, number>();

    constructor(dataDir: string) {
        this.file = path.join(dataDir, MACHINE_TOKENS_FILE);
        try {
            const v = JSON.parse(fs.readFileSync(this.file, 'utf8')) as unknown;
            if (Array.isArray(v)) this.list = v.filter((t) => t && typeof t.machine === 'string' && /^[0-9a-f]{64}$/.test(String(t.hash)));
        } catch { /* none yet */ }
    }

    private save(): void {
        fs.mkdirSync(path.dirname(this.file), { recursive: true });
        fs.writeFileSync(this.file, JSON.stringify(this.list, null, 2), { mode: 0o600 });
    }

    invite(now = Date.now()): { token: string; expiresAt: string } {
        for (const [h, until] of this.invites) if (until < now) this.invites.delete(h);
        const token = randomBytes(24).toString('base64url');
        this.invites.set(hashToken(token), now + INVITE_MS);
        return { token, expiresAt: new Date(now + INVITE_MS).toISOString() };
    }

    /** Redeems an invitation: a new agent token for `machine` (replacing an earlier one), or why not. */
    join(invite: string, machine: string, now = Date.now()): { token: string } | 'invalid' {
        const h = hashToken(invite);
        const until = this.invites.get(h);
        if (!until || until < now || !/^[a-z0-9-]{1,32}$/.test(machine)) return 'invalid';
        this.invites.delete(h);
        const token = randomBytes(32).toString('hex');
        this.list = this.list.filter((t) => t.machine !== machine);
        this.list.push({ machine, hash: hashToken(token), created: new Date(now).toISOString() });
        this.save();
        return { token };
    }

    /** A machine token; with `machine` only the one of that machine. */
    matches(raw: string, machine?: string): boolean {
        return this.list.some((t) => (!machine || t.machine === machine) && tokenMatches(t.hash, raw));
    }

    all(): { machine: string; created: string }[] {
        return this.list.map(({ machine, created }) => ({ machine, created }));
    }

    remove(machine: string): boolean {
        const before = this.list.length;
        this.list = this.list.filter((t) => t.machine !== machine);
        if (this.list.length === before) return false;
        this.save();
        return true;
    }
}

