// Writes webapp/js/release.js: the version from package.json and the notes of every released version from
// CHANGELOG.md, for "About" in the settings (all apps bring or load the web app, so this is the one place for them).
// "Unreleased" stays out, so editing it between releases leaves the file as it is; /release runs this after the bump.
//   node scripts/release-notes.mjs [--check]   (--check: exit 1 when the file is not up to date, writes nothing)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const TARGET = path.join(ROOT, 'webapp', 'js', 'release.js');

/**
 * The CHANGELOG wraps its lines at 120 characters; the web app renders line breaks as breaks, so a line that goes on
 * with the text above it (not a new item, heading, block or empty line) is joined to it.
 * @param {string} text
 */
export function unwrap(text) {
    const out = [];
    let fenced = false;
    for (const line of text.split('\n')) {
        const prev = out[out.length - 1];
        const fence = /^\s*```/.test(line);
        const continues = !fenced && !fence && prev !== undefined && prev.trim() !== '' && !/^\s*(#|```)/.test(prev) && line.trim() !== ''
            && !/^\s*([-*+]|\d+\.|#|>|\|)/.test(line);
        if (fence) fenced = !fenced;
        if (continues) out[out.length - 1] = `${prev} ${line.trim()}`;
        else out.push(line);
    }
    return out.join('\n');
}

/** The released versions, newest first: version, date and the Markdown below the heading. */
export function parseChangelog(text) {
    // Link definitions at the end ("[0.2.0]: https://…") belong to the headings, not to the notes
    const body = text.replace(/^\[[^\]]+\]:\s+\S+\s*$/gm, '');
    const parts = body.split(/^## \[([^\]]+)\](?: - (\d{4}-\d{2}-\d{2}))?\s*$/m);
    const releases = [];
    for (let i = 1; i < parts.length; i += 3) {
        const [version, date, notes] = [parts[i], parts[i + 1] || '', parts[i + 2].trim()];
        if (/^\d+\.\d+\.\d+$/.test(version)) releases.push({ version, date, notes: unwrap(notes) });
    }
    return releases;
}

export function releaseModule() {
    const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
    const releases = parseChangelog(fs.readFileSync(path.join(ROOT, 'CHANGELOG.md'), 'utf8'));
    return [
        '// Generated by scripts/release-notes.mjs from package.json and CHANGELOG.md; run `npm run release-notes` instead of',
        '// editing it.',
        '',
        '/** The version of OpenFolk this web app belongs to. */',
        `export const VERSION = ${JSON.stringify(version)};`,
        '',
        '/** @type {{ version: string, date: string, notes: string }[]} The released versions, newest first, notes in Markdown. */',
        `export const RELEASES = ${JSON.stringify(releases, null, 4)};`,
        '',
    ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
    const wanted = releaseModule();
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') : '';
    if (process.argv.includes('--check')) {
        if (current !== wanted) {
            console.error('webapp/js/release.js is not up to date: npm run release-notes');
            process.exit(1);
        }
    } else if (current !== wanted) {
        fs.writeFileSync(TARGET, wanted);
        console.log('webapp/js/release.js written');
    } else {
        console.log('webapp/js/release.js is up to date');
    }
}
